// Builds the site's service and team photographs from free stock (Pexels) so the
// whole set shares one crop and one grade, whoever shot the originals.
//
//   node scripts/prepare-photos.mjs [--only mens-beard,amara-lee] [--sheet <dir>]
//
// Reads scripts/photos.json (slug -> Pexels photo id + crop focus/zoom), downloads each
// original into .photos-cache/ (gitignored), then writes
//   public/images/services/<slug>.<hash>.webp   1200 x 900  (4:3; shown at 16:9, 4:5 and 1:1)
//   public/images/staff/<slug>.<hash>.webp       800 x 1000 (4:5; shown as tiles and avatars)
// The hash is of the file's content, so a changed photo is a new URL: nothing
// (browser, CDN, next/image cache) can keep serving the old picture.
//   src/lib/photos.generated.ts           slug -> { src, blur } for both sets
//
// The grade is deliberately mild and identical for every picture: slightly
// desaturated, a touch more contrast, shadows pulled toward the site's navy.
import sharp from "sharp";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "./_pw.mjs";

const args = parseArgs();
const manifest = JSON.parse(readFileSync("scripts/photos.json", "utf8"));
const only = args.only ? String(args.only).split(",") : null;
const cache = path.resolve(".photos-cache");
mkdirSync(cache, { recursive: true });

const SETS = {
  services: { w: 1200, h: 900, dir: "public/images/services", url: "/images/services" },
  staff: { w: 800, h: 1000, dir: "public/images/staff", url: "/images/staff" },
};

async function original(id) {
  const file = path.join(cache, `${id}.jpg`);
  if (!existsSync(file)) {
    const res = await fetch(`https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=2200`);
    if (!res.ok) throw new Error(`pexels ${id}: HTTP ${res.status}`);
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return file;
}

/** Largest crop of the target aspect, centred on `focus` and kept inside the frame. */
function cropBox(iw, ih, aspect, [fx, fy], zoom = 1) {
  let cw = iw;
  let ch = Math.round(cw / aspect);
  if (ch > ih) {
    ch = ih;
    cw = Math.round(ch * aspect);
  }
  // zoom < 1 takes a tighter crop (a closer view) around the focus.
  cw = Math.round(cw * zoom);
  ch = Math.round(ch * zoom);
  const left = Math.min(Math.max(Math.round(fx * iw - cw / 2), 0), iw - cw);
  const top = Math.min(Math.max(Math.round(fy * ih - ch / 2), 0), ih - ch);
  return { left, top, width: cw, height: ch };
}

/** The one grade every picture gets. */
async function grade(buf, w, h) {
  const base = await sharp(buf)
    .modulate({ saturation: 0.9 })
    .linear(1.06, -7)
    .toBuffer();
  // Navy multiplied in at low strength: pulls shadows toward the hero's colour.
  const tint = await sharp({ create: { width: w, height: h, channels: 4, background: { r: 38, g: 36, b: 78, alpha: 0.15 } } }).png().toBuffer();
  return sharp(base).composite([{ input: tint, blend: "multiply" }]).toBuffer();
}

const out = { services: {}, staff: {} };
const sheetTiles = [];
for (const [set, spec] of Object.entries(SETS)) {
  mkdirSync(path.resolve(spec.dir), { recursive: true });
  if (!only) for (const f of readdirSync(path.resolve(spec.dir))) rmSync(path.resolve(spec.dir, f)); // no stale files
  for (const [slug, item] of Object.entries(manifest[set])) {
    const file = await original(item.id);
    const meta = await sharp(file).metadata();
    const box = cropBox(meta.width, meta.height, spec.w / spec.h, item.focus ?? [0.5, 0.5], item.zoom ?? 1);
    const resized = await sharp(file).extract(box).resize(spec.w, spec.h, { fit: "fill" }).toBuffer();
    const graded = await grade(resized, spec.w, spec.h);
    const webp = await sharp(graded).webp({ quality: 80, effort: 5 }).toBuffer();
    const blur = await sharp(graded).resize(16, Math.round((16 * spec.h) / spec.w), { fit: "fill" }).webp({ quality: 30 }).toBuffer();
    const hash = createHash("sha1").update(webp).digest("hex").slice(0, 8);
    const name = `${slug}.${hash}.webp`;
    out[set][slug] = { src: `${spec.url}/${name}`, blur: `data:image/webp;base64,${blur.toString("base64")}` };
    if (!only || only.includes(slug)) {
      writeFileSync(path.resolve(spec.dir, name), webp);
      sheetTiles.push({ set, slug, id: item.id, kb: Math.round(webp.length / 1024), png: graded });
    }
  }
}

const dump = (obj) =>
  Object.entries(obj)
    .map(([k, v]) => `  ${JSON.stringify(k)}: { src: ${JSON.stringify(v.src)}, blur: ${JSON.stringify(v.blur)} },`)
    .join("\n");
writeFileSync(
  path.resolve("src/lib/photos.generated.ts"),
  `// Generated by scripts/prepare-photos.mjs — do not edit by hand.\n` +
    `// Stock photographs (Pexels, see public/ds/CREDITS.md) cropped and graded to one look,\n` +
    `// with blur placeholders. Keyed by service slug / staff slug.\n\n` +
    `export type Photo = { src: string; blur: string };\n\n` +
    `export const SERVICE_PHOTOS: Record<string, Photo> = {\n${dump(out.services)}\n};\n\n` +
    `export const STAFF_PHOTOS: Record<string, Photo> = {\n${dump(out.staff)}\n};\n`,
);

if (args.sheet) {
  const dir = path.resolve(String(args.sheet));
  mkdirSync(dir, { recursive: true });
  for (const [set, W, H] of [["services", 420, 315], ["staff", 252, 315]]) {
    const tiles = sheetTiles.filter((t) => t.set === set);
    if (!tiles.length) continue;
    const bufs = await Promise.all(tiles.map((t) => sharp(t.png).resize(W, H, { fit: "cover" }).toBuffer()));
    const labels = tiles.map((t) =>
      Buffer.from(`<svg width="${W}" height="22" xmlns="http://www.w3.org/2000/svg"><rect width="100%" height="100%" fill="#fff"/><text x="3" y="16" font-family="Arial" font-size="14" font-weight="700" fill="#111">${t.slug} · ${t.id} · ${t.kb}KB</text></svg>`),
    );
    const cols = set === "services" ? 4 : 7;
    const rows = Math.ceil(tiles.length / cols);
    await sharp({ create: { width: cols * (W + 4), height: rows * (H + 26), channels: 3, background: "#fff" } })
      .composite(bufs.flatMap((input, i) => [
        { input, left: (i % cols) * (W + 4), top: Math.floor(i / cols) * (H + 26) },
        { input: labels[i], left: (i % cols) * (W + 4), top: Math.floor(i / cols) * (H + 26) + H },
      ]))
      .png()
      .toFile(path.join(dir, `${set}.png`));
  }
}
