// Builds supabase/setup.sql: every migration in order, then the demo seed, as
// ONE file for a fresh database (paste it into the Supabase SQL editor).
//
//   npm run db:setup          write supabase/setup.sql
//   npm run db:setup:check    exit 1 if the committed file is out of date (CI)
//
// supabase/migrations/* stay the source of truth and the upgrade path for an
// existing project (they are tracked by filename); setup.sql is generated.
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const dir = "supabase";
const out = path.join(dir, "setup.sql");

const names = (await readdir(path.join(dir, "migrations"))).filter((f) => f.endsWith(".sql")).sort();
if (names.length === 0) throw new Error("no migrations found");

// 0001, 0002, … with no gaps or duplicates, so nothing is silently skipped.
names.forEach((name, i) => {
  const n = Number(name.slice(0, 4));
  if (!/^\d{4}_/.test(name) || n !== i + 1) {
    throw new Error(`migration numbering is not contiguous at ${name} (expected ${String(i + 1).padStart(4, "0")}_…)`);
  }
});

const lf = (s) => s.replace(/\r\n/g, "\n").replace(/\s+$/, "") + "\n";
const banner = (label) => `\n-- ${"=".repeat(76)}\n-- ${label}\n-- ${"=".repeat(76)}\n\n`;

const sources = [
  ...names.map((n) => ({ label: `migrations/${n}`, file: path.join(dir, "migrations", n) })),
  { label: "seed.sql — demo salon, services, staff, hours", file: path.join(dir, "seed.sql") },
];

let text =
  `-- justhairs — complete database setup (schema, RPCs, cron jobs, demo salon).\n` +
  `--\n` +
  `-- GENERATED by scripts/build-setup-sql.mjs — do not edit. Change a migration or\n` +
  `-- seed.sql, then run \`npm run db:setup\`.\n` +
  `--\n` +
  `-- Fresh project only: paste this whole file into the Supabase SQL editor and run it.\n` +
  `-- Enable the pg_cron extension first (Database → Extensions).\n` +
  `-- An existing project should apply just the newer files in supabase/migrations/.\n`;
for (const s of sources) text += banner(s.label) + lf(await readFile(s.file, "utf8"));

if (process.argv.includes("--check")) {
  const current = await readFile(out, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== text) {
    console.error(`${out} is out of date — run \`npm run db:setup\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${out} is up to date (${sources.length} sections).`);
} else {
  await writeFile(out, text, "utf8");
  console.log(`wrote ${out}: ${names.length} migrations + seed, ${text.split("\n").length} lines`);
}
