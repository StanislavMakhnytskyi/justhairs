// Generates tiny base64 blur previews for every image in the Supabase Storage
// "assets" bucket, so next/image can show a blurred version of the real photo
// while it loads.
//
//   node --env-file=.env.local scripts/gen-blur.mjs
//
// Re-run whenever the imagery changes. Output: src/lib/blur.generated.ts

import { createClient } from "@supabase/supabase-js";
// KNOWN ISSUE (CODE_REVIEW.md #22): sharp isn't declared in package.json at
// all — this only resolves because Next pulls it in as its own transitive
// dependency. Works today by accident; add it to devDependencies directly.
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY ?? process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !key) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL / Supabase key.");
  process.exit(1);
}

const supabase = createClient(url, key, { auth: { persistSession: false } });
const BUCKET = "assets";
const PREFIXES = ["", "services", "staff"];

async function listAll() {
  const paths = [];
  for (const prefix of PREFIXES) {
    const { data, error } = await supabase.storage.from(BUCKET).list(prefix, { limit: 200 });
    if (error) throw error;
    for (const entry of data ?? []) {
      // directories come back without metadata
      if (!entry.metadata) continue;
      // The bucket also holds the hero video; only images get a blur preview.
      if (!/\.(webp|png|jpe?g|avif)$/i.test(entry.name)) continue;
      paths.push(prefix ? `${prefix}/${entry.name}` : entry.name);
    }
  }
  return paths.sort();
}

async function blurFor(path) {
  const { data } = supabase.storage.from(BUCKET).getPublicUrl(path);
  const res = await fetch(data.publicUrl);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const out = await sharp(buf).resize(16, 16, { fit: "inside" }).webp({ quality: 20 }).toBuffer();
  return `data:image/webp;base64,${out.toString("base64")}`;
}

async function main() {
  const paths = await listAll();
  if (!paths.length) {
    console.error(`No objects found in the "${BUCKET}" bucket.`);
    process.exit(1);
  }

  const entries = [];
  for (const path of paths) {
    entries.push([path, await blurFor(path)]);
    process.stdout.write(`  ${path}\n`);
  }

  const body = entries
    .map(([p, d]) => `  ${JSON.stringify(p)}: ${JSON.stringify(d)},`)
    .join("\n");

  writeFileSync(
    "src/lib/blur.generated.ts",
    `// Generated by scripts/gen-blur.mjs — do not edit by hand.\n` +
      `// Tiny blurred previews keyed by their path in the Storage "assets" bucket.\n\n` +
      `export const BLUR: Record<string, string> = {\n${body}\n};\n`,
    "utf8",
  );

  console.log(`\nWrote src/lib/blur.generated.ts — ${entries.length} previews.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
